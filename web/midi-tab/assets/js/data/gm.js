function programVoice(p) {
  if (p === 24) return "nylon";
  if (p === 25) return "steel";
  if (p >= 26 && p <= 31) return "electric";
  if (p >= 32 && p <= 39) return "bass";
  if (p === 105) return "banjo";
  if (p >= 104 && p <= 108) return "mandolin";
  if (p < 8) return "piano";
  if (p < 16) return "bell";
  if (p < 24) return "organ";
  if (p < 56) return p === 45 || p === 46 ? "nylon" : "strings";
  if (p < 72) return "brass";
  if (p < 80) return "flute";
  return "synth";
}
